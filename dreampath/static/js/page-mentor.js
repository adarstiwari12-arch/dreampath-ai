/* page-mentor.js - AI mentor chat. Messages are rendered with textContent only. */
document.addEventListener("DOMContentLoaded", () => {
  const root = document.querySelector("[data-mentor]");
  if (!root) return;
  const { api, el, toast, formatDuration, formatDate } = window.DP;
  const log = root.querySelector("[data-log]");
  const form = root.querySelector("[data-form]");
  const input = document.getElementById("msg");
  const mode = root.querySelector("[data-mode]");
  const sendBtn = form.querySelector("button");
  const initials = (document.querySelector(".avatar")?.textContent || "You").trim().slice(0, 2);

  const MODE_LLM = "Answers are generated by the AI mentor using your progress data.";
  const MODE_RULES = "Showing rule-based answers from your progress data. Add an API key to enable the AI mentor.";

  function bubble(role, text, extra = "") {
    const node = el("div", { class: `msg ${role}` },
      el("span", { class: "av", text: role === "user" ? initials : "AI" }),
      el("div", { class: `bubble ${extra}`.trim(), text }));
    log.append(node); log.scrollTop = log.scrollHeight;
    return node.querySelector(".bubble");
  }

  async function ask(message) {
    message = message.trim();
    if (!message) return;
    bubble("user", message); input.value = "";
    const typing = bubble("assistant", "Thinking...", "typing");
    sendBtn.disabled = true;
    try {
      const r = await api("POST", "/api/ai/mentor", { message });
      typing.className = "bubble"; typing.textContent = r.reply;
      mode.textContent = r.source === "llm" ? MODE_LLM : MODE_RULES;
    } catch (e) { typing.closest(".msg").remove(); toast(e.message, "error"); }
    finally { sendBtn.disabled = false; input.focus(); log.scrollTop = log.scrollHeight; }
  }

  form.addEventListener("submit", (e) => { e.preventDefault(); ask(input.value); });
  root.querySelectorAll("[data-suggest] button").forEach((b) => b.addEventListener("click", () => ask(b.textContent)));
  root.querySelector("[data-clear]").addEventListener("click", async () => {
    try {
      await api("DELETE", "/api/ai/mentor");
      log.replaceChildren(); bubble("assistant", "Chat cleared. Ask me anything about your roadmap.");
    } catch (e) { toast(e.message, "error"); }
  });

  async function loadContext() {
    const d = await api("GET", "/api/roadmap");
    const m = d.meter;
    const rows = [
      ["Stream", d.stream.name], ["Target", `${d.target_lpa} LPA (${d.tier.name})`],
      ["Dream Meter", `${m.percent}%`], ["Lessons done", `${m.done_count}/${m.total_count}`],
      ["Next lesson", m.next_step ? m.next_step.title : "All done"],
      ["Finish by", m.done_count === m.total_count ? "Complete" : formatDate(d.plan.finish_date)],
    ];
    root.querySelector("[data-context]").replaceChildren(...rows.map(([k, v]) =>
      el("li", {}, el("span", { text: k }), el("span", { class: "strong", text: v }))));
  }

  (async () => {
    try {
      const [h] = await Promise.all([api("GET", "/api/ai/mentor"), loadContext()]);
      mode.textContent = h.llm ? MODE_LLM : MODE_RULES;
      if (h.messages.length) h.messages.forEach((m) => bubble(m.role, m.content));
      else bubble("assistant", "Hi! I can see your roadmap and progress. Ask what to do next, how long it will take, or how to prepare for interviews.");
      const prefill = new URLSearchParams(window.location.search).get("q");
      if (prefill) { input.value = prefill.slice(0, 600); input.focus(); }
    } catch (e) {
      if (e.status === 409) window.location.assign("/setup"); else toast(e.message, "error");
    }
  })();
});
